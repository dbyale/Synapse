import fs from 'fs';
import path from 'path';
import fetch from 'node-fetch';

// Records which archives the pinned llama.cpp nightly actually publishes.
// src/__tests__/llamaAssetsSnapshot.test.ts checks every asset Synapse builds a
// URL for against this file, so a target upstream renamed or dropped (CUDA
// 13.4 -> 13.5 at v1.0.0) fails a test instead of a user's download. Run this
// whenever package.json ▸ binaryVersions.llama changes; the test looks for
// fixtures/llama-assets.<pin>.json and says so when the file is missing.
//
//   npx ts-node .erb/scripts/llama-assets.ts

const JSON_PATH = path.join(__dirname, '../../package.json');
const FIXTURE_DIR = path.join(__dirname, '../../src/__tests__/fixtures');

const packageJson = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
const LLAMA_VERSION: string = packageJson.binaryVersions.llama;

if (!/^b\d+$/.test(LLAMA_VERSION)) {
  throw new Error(
    `binaryVersions.llama must be a nightly tag (bXXXXX), got ${LLAMA_VERSION}`,
  );
}

async function main(): Promise<void> {
  const url = `https://api.github.com/repos/ggml-org/llama.cpp/releases/tags/${LLAMA_VERSION}`;
  const res = await fetch(url, {
    headers: {
      Accept: 'application/vnd.github+json',
      'User-Agent': 'synapse-llama-assets',
    },
  });
  if (!res.ok) {
    throw new Error(`${url} -> ${res.status} ${res.statusText}`);
  }
  const release = (await res.json()) as { tag_name?: string; assets?: any[] };
  const assets = (release.assets ?? [])
    .map((asset: any) => asset.name as string)
    .filter(Boolean)
    .sort();

  if (assets.length === 0) {
    throw new Error(
      `${release.tag_name ?? LLAMA_VERSION} publishes no assets — ` +
        'is the pin a semver tag? Semver releases carry no binaries.',
    );
  }

  fs.mkdirSync(FIXTURE_DIR, { recursive: true });
  const out = path.join(FIXTURE_DIR, `llama-assets.${LLAMA_VERSION}.json`);
  fs.writeFileSync(
    out,
    `${JSON.stringify(
      {
        tag: release.tag_name ?? LLAMA_VERSION,
        source: url,
        note: 'Generated by .erb/scripts/llama-assets.ts. Do not edit by hand.',
        assets,
      },
      null,
      2,
    )}\n`,
  );

  console.log(`${release.tag_name ?? LLAMA_VERSION}: ${assets.length} assets`);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
